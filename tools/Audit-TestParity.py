def load_route_audit(csharp_root: Path):
    tool_path = csharp_root / "tools" / "Audit-LegacyRoutes.py"
    if not tool_path.is_file():
        raise SystemExit(f"route audit tool not found: {tool_path}")
    spec = importlib.util.spec_from_file_location("audit_legacy_routes", tool_path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"could not load route audit tool: {tool_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def analyze_routes(csharp_root: Path, python_root: Path, route_audit_module: Any):
    legacy = route_audit_module.LegacyAnalyzer(python_root)
    legacy.analyze()
    csharp = route_audit_module.CSharpAnalyzer(csharp_root)
    csharp.analyze()
    coverage = route_audit_module.build_coverage(legacy, csharp)
    return legacy, csharp, coverage


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Offline Python/C# HTTP test parity audit")
    parser.add_argument("--python-root", required=True)
    parser.add_argument("--csharp-root", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args(argv)

    python_root = Path(args.python_root).resolve()
    csharp_root = Path(args.csharp_root).resolve()
    output = Path(args.output).resolve()
    if not python_root.is_dir():
        raise SystemExit(f"python root not found: {python_root}")
    if not csharp_root.is_dir():
        raise SystemExit(f"csharp root not found: {csharp_root}")

    route_audit_module = load_route_audit(csharp_root)
    legacy, csharp, coverage = analyze_routes(
        csharp_root, python_root, route_audit_module
    )
    python_tests = collect_python_tests(python_root)
    csharp_tests = collect_csharp_tests(csharp_root)
    report = build_report(
        python_root,
        csharp_root,
        legacy,
        csharp,
        coverage,
        route_audit_module,
        python_tests,
        csharp_tests,
    )

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    md_path = output.with_suffix(".md")
    md_path.write_text(render_markdown(report), encoding="utf-8")
    summary = report["summary"]
    print(
        "wrote {json} and {md}: business={business} py_hits={py} cs_hits={cs} "
        "py_unresolved={pu} cs_unresolved={cu}".format(
            json=output,
            md=md_path,
            business=summary["business_routes_total"],
            py=summary["business_routes_with_python_static_hit"],
            cs=summary["business_routes_with_csharp_static_hit"],
            pu=summary["python_http_calls_unresolved"],
            cu=summary["csharp_http_calls_unresolved"],
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
