def iter_source_files(
    root: Path,
    suffix: str,
    skip_dirs: Iterable[str] = SKIP_DIRS,
) -> list[Path]:
    """Return source files below *root*, never descending into build output."""
    skip = set(skip_dirs)
    result: list[Path] = []
    if not root.is_dir():
        return result
    for path in sorted(root.rglob(f"*{suffix}")):
        rel_parts = path.relative_to(root).parts[:-1]
        if any(part in skip for part in rel_parts):
            continue
        if path.is_file():
            result.append(path)
    return result


def strip_query_fragment(route: str) -> tuple[str, str]:
    """Split a route into its path and its query/fragment suffix.

    Query strings are never part of Flask/ASP.NET route registration.  Keeping
    them in the key produced false negatives in the previous auditor.
    """
    value = str(route or "")
    fragment = ""
    if "#" in value:
        value, fragment = value.split("#", 1)
        fragment = "#" + fragment
    query = ""
    if "?" in value:
        value, query = value.split("?", 1)
        query = "?" + query
    return value, query + fragment


def _looks_like_http_route(route: str | None) -> bool:
    """Reject resolver artefacts such as ``/v1{}`` (no real path separator)."""
    if not route or not route.startswith("/"):
        return False
    path = strip_query_fragment(route)[0]
    if path.count("/") >= 2:
        return True
    return path in {"/ping", "/error", "/urls", "/warning", "/docs"} or path.startswith("/docs/")


def _first_word(value: str) -> str:
    return value.strip("/").split("/", 1)[0].lower() if value.strip("/") else "root"


