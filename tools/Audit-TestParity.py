@dataclass
class Token:
    kind: str
    value: str
    start: int
    end: int
    line: int
    template: str | None = None
    parts: list[dict[str, str]] | None = None
    string_kind: str = ""


class CSharpLexer:
    """Small C# lexer that isolates strings/comments from code.

    It supports regular, verbatim, raw (``\"\"\"...\"\"\"``) and interpolated
    strings.  Interpolation holes are scanned with nested string/brace awareness
    so ``$"/v1/users/{user["_id"]}"`` becomes ``/v1/users/{}`` instead of being
    truncated at the inner quote.
    """

    def __init__(self, text: str):
        self.text = text
        self.n = len(text)
        self.line_starts = [0] + [match.end() for match in re.finditer(r"\n", text)]
        self.tokens: list[Token] = []
        self.masked_chars = list(text)

    def line_of(self, pos: int) -> int:
        return bisect.bisect_right(self.line_starts, pos)

    def _mask(self, start: int, end: int) -> None:
        for index in range(start, min(end, self.n)):
            if self.masked_chars[index] not in "\r\n":
                self.masked_chars[index] = " "

    def tokenize(self) -> tuple[list[Token], str]:
        i = 0
        while i < self.n:
            ch = self.text[i]
            if ch in " \t\r\n":
                i += 1
                continue
            if ch == "/" and i + 1 < self.n and self.text[i + 1] == "/":
                start = i
                i = self.text.find("\n", i)
                if i < 0:
                    i = self.n
                self._mask(start, i)
                continue
            if ch == "/" and i + 1 < self.n and self.text[i + 1] == "*":
                start = i
                end = self.text.find("*/", i + 2)
                i = self.n if end < 0 else end + 2
                self._mask(start, i)
                continue
            if ch == "#" and (i == 0 or self.text[i - 1] == "\n"):
                start = i
                i = self.text.find("\n", i)
                if i < 0:
                    i = self.n
                self._mask(start, i)
                continue
            if ch == '"' or (ch in "$@" and self._has_string_prefix(i)):
                token, i = self._scan_string(i)
                self.tokens.append(token)
                self._mask(token.start, token.end)
                continue
            if ch == "'":
                start = i
                i += 1
                while i < self.n:
                    if self.text[i] == "\\":
                        i += 2
                        continue
                    if self.text[i] == "'":
                        i += 1
                        break
                    i += 1
                self._mask(start, i)
                continue
            if ch.isalpha() or ch == "_":
                start = i
                i += 1
                while i < self.n and (self.text[i].isalnum() or self.text[i] == "_"):
                    i += 1
                self.tokens.append(Token("ident", self.text[start:i], start, i, self.line_of(start)))
                continue
            if ch.isdigit():
                start = i
                i += 1
                while i < self.n and (self.text[i].isalnum() or self.text[i] in "._"):
                    i += 1
                self.tokens.append(Token("number", self.text[start:i], start, i, self.line_of(start)))
                continue
            for op in (
                "=>",
                "==",
                "!=",
                "<=",
                ">=",
                "&&",
                "||",
                "??",
                "?.",
                "::",
                "++",
                "--",
                "+=",
                "-=",
                "*=",
                "/=",
            ):
                if self.text.startswith(op, i):
                    self.tokens.append(Token("punct", op, i, i + len(op), self.line_of(i)))
                    i += len(op)
                    break
            else:
                self.tokens.append(Token("punct", ch, i, i + 1, self.line_of(i)))
                i += 1
        return self.tokens, "".join(self.masked_chars)

    def _has_string_prefix(self, i: int) -> bool:
        j = i
        while j < self.n and self.text[j] in "$@":
            j += 1
        return j < self.n and self.text[j] == '"'

    def _scan_string(self, i: int) -> tuple[Token, int]:
        start = i
        dollars = 0
        verbatim = False
        while i < self.n and self.text[i] in "$@":
            if self.text[i] == "$":
                dollars += 1
            else:
                verbatim = True
            i += 1
        quote_start = i
        quote_count = 0
        while quote_start + quote_count < self.n and self.text[quote_start + quote_count] == '"':
            quote_count += 1
        if quote_count >= 3:
            return self._scan_raw(start, quote_start, quote_count, dollars)
        return self._scan_regular(start, quote_start, dollars, verbatim)

    def _scan_regular(
        self, start: int, quote_start: int, dollars: int, verbatim: bool
    ) -> tuple[Token, int]:
        interp = dollars > 0
        parts: list[dict[str, str]] = []
        buffer: list[str] = []
        i = quote_start + 1
        while i < self.n:
            ch = self.text[i]
            if verbatim and ch == '"':
                if i + 1 < self.n and self.text[i + 1] == '"':
                    buffer.append('"')
                    i += 2
                    continue
                i += 1
                break
            if not verbatim and ch == "\\":
                if i + 1 < self.n:
                    esc = self.text[i + 1]
                    mapping = {
                        '"': '"',
                        "\\": "\\",
                        "n": "\n",
                        "r": "\r",
                        "t": "\t",
                        "0": "\0",
                    }
                    if esc == "u" and i + 5 < self.n:
                        try:
                            buffer.append(chr(int(self.text[i + 2 : i + 6], 16)))
                            i += 6
                            continue
                        except ValueError:
                            pass
                    buffer.append(mapping.get(esc, esc))
                    i += 2
                    continue
                i += 1
                continue
            if not verbatim and ch == '"':
                i += 1
                break
            if interp and ch == "{":
                if i + 1 < self.n and self.text[i + 1] == "{":
                    buffer.append("{")
                    i += 2
                    continue
                if buffer:
                    parts.append({"kind": "lit", "text": "".join(buffer)})
                    buffer = []
                end = self._scan_hole(i)
                parts.append({"kind": "expr", "text": self.text[i + 1 : end]})
                i = end + 1
                continue
            if interp and ch == "}":
                if i + 1 < self.n and self.text[i + 1] == "}":
                    buffer.append("}")
                    i += 2
                    continue
                buffer.append("}")
                i += 1
                continue
            buffer.append(ch)
            i += 1
        if buffer:
            parts.append({"kind": "lit", "text": "".join(buffer)})
        template = "".join(part["text"] if part["kind"] == "lit" else "{}" for part in parts)
        kind = "interpolated" if interp else ("verbatim" if verbatim else "regular")
        token = Token(
            "string",
            self.text[start:i],
            start,
            i,
            self.line_of(start),
            template=template,
            parts=parts,
            string_kind=kind,
        )
        return token, i

    def _scan_raw(
        self, start: int, quote_start: int, quote_count: int, dollars: int
    ) -> tuple[Token, int]:
        delimiter = '"' * quote_count
        content_start = quote_start + quote_count
        close = self.text.find(delimiter, content_start)
        if close < 0:
            close = self.n
            i = self.n
        else:
            i = close + quote_count
        content = self.text[content_start:close]
        if dollars == 0:
            parts = [{"kind": "lit", "text": content}]
        else:
            parts = self._split_raw_holes(content, dollars)
        template = "".join(part["text"] if part["kind"] == "lit" else "{}" for part in parts)
        token = Token(
            "string",
            self.text[start:i],
            start,
            i,
            self.line_of(start),
            template=template,
            parts=parts,
            string_kind="raw_interpolated" if dollars else "raw",
        )
        return token, i

    def _split_raw_holes(self, content: str, dollars: int) -> list[dict[str, str]]:
        parts: list[dict[str, str]] = []
        buffer: list[str] = []
        i = 0
        while i < len(content):
            if content[i] == "{":
                run = 1
                while i + run < len(content) and content[i + run] == "{":
                    run += 1
                if run >= dollars:
                    if buffer:
                        parts.append({"kind": "lit", "text": "".join(buffer)})
                        buffer = []
                    end = self._scan_raw_hole(content, i + dollars, dollars)
                    parts.append({"kind": "expr", "text": content[i + dollars : end]})
                    i = end + dollars
                    continue
                buffer.append("{" * run)
                i += run
                continue
            buffer.append(content[i])
            i += 1
        if buffer:
            parts.append({"kind": "lit", "text": "".join(buffer)})
        return parts

    def _scan_raw_hole(self, content: str, start: int, dollars: int) -> int:
        depth = 1
        i = start
        while i < len(content):
            ch = content[i]
            if ch == "{":
                depth += 1
                i += 1
                continue
            if ch == "}":
                run = 1
                while i + run < len(content) and content[i + run] == "}":
                    run += 1
                if depth == 1 and run >= dollars:
                    return i
                depth -= 1
                i += run
                continue
            if ch == '"':
                i = self._skip_literal_at(content, i)
                continue
            i += 1
        return len(content)

    def _skip_literal_at(self, text: str, i: int) -> int:
        # Skip a nested string/char literal inside an interpolation hole.
        if text[i] == "'":
            i += 1
            while i < len(text):
                if text[i] == "\\":
                    i += 2
                    continue
                if text[i] == "'":
                    return i + 1
                i += 1
            return i
        payload = text[i:]
        lexer = CSharpLexer(payload)
        token, end = lexer._scan_string(0)
        return i + end

    def _scan_hole(self, open_index: int) -> int:
        depth = 1
        i = open_index + 1
        while i < self.n:
            ch = self.text[i]
            if ch == '"' or (ch in "$@" and self._has_string_prefix(i)):
                token, i = self._scan_string(i)
                continue
            if ch == "'":
                i += 1
                while i < self.n:
                    if self.text[i] == "\\":
                        i += 2
                        continue
                    if self.text[i] == "'":
                        i += 1
                        break
                    i += 1
                continue
            if ch == "/" and i + 1 < self.n and self.text[i + 1] == "/":
                i = self.text.find("\n", i)
                if i < 0:
                    return self.n - 1
                continue
            if ch == "/" and i + 1 < self.n and self.text[i + 1] == "*":
                end = self.text.find("*/", i + 2)
                i = self.n if end < 0 else end + 2
                continue
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    return i
            i += 1
        return self.n - 1


