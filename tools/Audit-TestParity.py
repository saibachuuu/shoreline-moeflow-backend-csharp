def _name_of(node: ast.AST) -> str:
    try:
        return ast.unparse(node)
    except Exception:
        return type(node).__name__


def _literal_int(node: ast.AST) -> int | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, int) and not isinstance(node.value, bool):
        return node.value
    return None


def _is_http_receiver(node: ast.AST) -> bool:
    """Reject ``dict.get(...)`` and friends; accept test-client receivers."""
    root: ast.AST = node
    while isinstance(root, (ast.Attribute, ast.Subscript)):
        root = root.value
    if isinstance(root, ast.Name):
        name = root.id.lower()
        return (
            name in {"self", "client", "http", "anonymous"}
            or name.endswith("client")
            or name.endswith("http")
        )
    return False


class _PythonRouteResolver:
    def __init__(
        self,
        class_env: dict[str, ast.AST],
        self_attrs: dict[str, ast.AST],
        method_returns: dict[str, list[ast.AST]],
        local_env: dict[str, list[tuple[int, ast.AST]]],
        param_env: dict[str, ast.AST] | None = None,
    ):
        self.class_env = class_env
        self.self_attrs = self_attrs
        self.method_returns = method_returns
        self.local_env = local_env
        self.param_env = param_env or {}
        self._seen: set[int] = set()

    def resolve(self, node: ast.AST, use_line: int = 10**9) -> tuple[str | None, str]:
        if id(node) in self._seen:
            return None, "cycle"
        self._seen.add(id(node))
        try:
            return self._resolve(node, use_line)
        finally:
            self._seen.discard(id(node))

    def _resolve(self, node: ast.AST, use_line: int) -> tuple[str | None, str]:
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            return node.value, "literal"
        if isinstance(node, ast.JoinedStr):
            parts: list[str] = []
            for value in node.values:
                if isinstance(value, ast.Constant) and isinstance(value.value, str):
                    parts.append(value.value)
                elif isinstance(value, ast.FormattedValue):
                    parts.append("{}")
                else:
                    return None, "unsupported f-string part"
            return "".join(parts), "fstring"
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            left, lvia = self.resolve(node.left, use_line)
            right, rvia = self.resolve(node.right, use_line)
            if left is not None and right is not None:
                return left + right, f"concat:{lvia}+{rvia}"
            if left is not None and left.startswith("/") and (
                left.endswith("/")
                or isinstance(node.right, (ast.Name, ast.Attribute, ast.Call, ast.Subscript))
            ):
                # ``"/v1/admin/users/" + str(user.id)`` and
                # ``"/v1/users/user" + id`` both carry a literal route prefix.
                if _name_of(node.right).startswith(("str(", "int(", "self.", "user.", "obj.")) or isinstance(
                    node.right, (ast.Name, ast.Attribute, ast.Subscript)
                ):
                    return left + "{}", "concat:literal+placeholder"
            return None, "binary add not statically resolvable"
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
            attr = node.func.attr
            if attr == "format":
                base, via = self.resolve(node.func.value, use_line)
                if base is None:
                    return None, "format base unresolved"
                # Replace both positional and named fields with one token.
                rendered = re.sub(r"\{[^{}]*\}", "{}", base)
                return rendered, f"format:{via}"
            if attr in self.method_returns and not node.args:
                returns = self.method_returns[attr]
                if returns:
                    return self.resolve(returns[-1], use_line)
            return None, f"call .{attr} unresolved"
        if isinstance(node, ast.Name):
            if node.id in self.param_env:
                return self.resolve(self.param_env[node.id], use_line)
            entries = self.local_env.get(node.id)
            if entries:
                candidates = [item for item in entries if item[0] < use_line]
                chosen = candidates[-1] if candidates else entries[-1]
                return self.resolve(chosen[1], chosen[0])
            if node.id in self.class_env:
                return self.resolve(self.class_env[node.id], use_line)
            return None, f"name {node.id} unresolved"
        if isinstance(node, ast.Attribute):
            if isinstance(node.value, ast.Name) and node.value.id == "self":
                if node.attr in self.self_attrs:
                    return self.resolve(self.self_attrs[node.attr], use_line)
                if node.attr in self.class_env:
                    return self.resolve(self.class_env[node.attr], use_line)
            return None, f"attribute {_name_of(node)} unresolved"
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            return None, f"call {node.func.id} unresolved"
        return None, f"expression {type(node).__name__} unresolved"


def _python_function_evidence(node: ast.AST) -> dict[str, Any]:
    assertions: set[str] = set()
    expected_status: set[int] = set()
    error_assertions: set[str] = set()
    header_checks: set[str] = set()
    digest_checks: set[str] = set()
    assertion_count = 0

    for child in ast.walk(node):
        if isinstance(child, ast.Assert):
            assertions.add("assert")
            assertion_count += 1
        if isinstance(child, ast.Call) and isinstance(child.func, ast.Attribute):
            attr = child.func.attr
            if attr.startswith("assert"):
                assertions.add(attr)
                assertion_count += 1
                if attr == "assertErrorEqual" and len(child.args) >= 2:
                    error_assertions.add(_name_of(child.args[1]))
                # ``assertEqual(response.status_code, 200)`` and variants.
                values = [*child.args, *[kw.value for kw in child.keywords]]
                status_seen = any("status_code" in _name_of(value) for value in values)
                if status_seen:
                    for value in values:
                        number = _literal_int(value)
                        if number is not None:
                            expected_status.add(number)
            if attr in {"get", "getlist"} and any(
                isinstance(arg, ast.Constant)
                and isinstance(arg.value, str)
                and HEADER_NAME_RE.match(arg.value)
                for arg in child.args
            ):
                header_checks.add("headers.get")
        if isinstance(child, ast.Compare):
            side_text = _name_of(child.left)
            if "status_code" in side_text:
                for comparator in child.comparators:
                    number = _literal_int(comparator)
                    if number is not None:
                        expected_status.add(number)
            if '"code"' in side_text or "'code'" in side_text or ".get('code')" in side_text:
                for comparator in child.comparators:
                    number = _literal_int(comparator)
                    if number is not None:
                        error_assertions.add(str(number))
        if isinstance(child, ast.Attribute) and child.attr.lower() in {"headers", "header"}:
            header_checks.add(_name_of(child))
        if isinstance(child, ast.Constant) and isinstance(child.value, str):
            if HEADER_NAME_RE.match(child.value):
                header_checks.add(child.value)
        if isinstance(child, (ast.Name, ast.Attribute, ast.Call)):
            text = _name_of(child)
            if DIGEST_RE.search(text):
                digest_checks.add(text[:120])

    return {
        "assertions": sorted(assertions),
        "assertion_count": assertion_count,
        "expected_status": sorted(expected_status),
        "error_assertions": sorted(error_assertions),
        "header_assertions": sorted(header_checks),
        "digest_assertions": sorted(digest_checks)[:20],
    }


@dataclass
class PythonFunction:
    name: str
    class_name: str | None
    line: int
    is_test: bool
    node: ast.AST
    local_env: dict[str, list[tuple[int, ast.AST]]] = field(default_factory=dict)
    param_names: list[str] = field(default_factory=list)
    evidence: dict[str, Any] = field(default_factory=dict)


class PythonTestAnalyzer(ast.NodeVisitor):
    """Collect HTTP calls from one Python test module."""

    def __init__(self, filepath: Path):
        self.filepath = filepath
        self.classes: list[dict[str, Any]] = []
        self.functions: list[PythonFunction] = []
        self.module_functions: list[PythonFunction] = []
        self.raw_calls: list[dict[str, Any]] = []
        self.unresolved: list[dict[str, Any]] = []
        self._parents: dict[int, ast.AST] = {}

    # -- class/context collection -----------------------------------------
    def _index_tree(self, tree: ast.AST) -> None:
        self._parents = {}
        for parent in ast.walk(tree):
            for child in ast.iter_child_nodes(parent):
                self._parents[id(child)] = parent

    def _collect_functions(self, tree: ast.AST) -> None:
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            class_name = self._class_name_for(node)
            fn = PythonFunction(
                name=node.name,
                class_name=class_name,
                line=node.lineno,
                is_test=node.name.startswith("test"),
                node=node,
                local_env=self._collect_local_env(node),
                param_names=[arg.arg for arg in node.args.args if arg.arg != "self"],
            )
            fn.evidence = _python_function_evidence(node)
            if class_name is None:
                self.module_functions.append(fn)
            else:
                self.functions.append(fn)

    def _class_name_for(self, node: ast.AST) -> str | None:
        current: ast.AST | None = node
        while current is not None:
            if isinstance(current, ast.ClassDef):
                return current.name
            current = self._parents.get(id(current))
        return None

    def _collect_class_context(self, node: ast.ClassDef) -> None:
        class_env: dict[str, ast.AST] = {}
        self_attrs: dict[str, ast.AST] = {}
        method_returns: dict[str, list[ast.AST]] = {}
        for stmt in node.body:
            if isinstance(stmt, ast.Assign):
                for target in stmt.targets:
                    if isinstance(target, ast.Name):
                        class_env[target.id] = stmt.value
                    elif (
                        isinstance(target, ast.Attribute)
                        and isinstance(target.value, ast.Name)
                        and target.value.id == "self"
                    ):
                        self_attrs[target.attr] = stmt.value
            elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.value:
                class_env[stmt.target.id] = stmt.value
            elif isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for child in ast.walk(stmt):
                    if (
                        isinstance(child, ast.Assign)
                        and isinstance(child.targets[0], ast.Attribute)
                        and isinstance(child.targets[0].value, ast.Name)
                        and child.targets[0].value.id == "self"
                    ):
                        self_attrs[child.targets[0].attr] = child.value
                    if isinstance(child, ast.Return) and child.value is not None:
                        method_returns.setdefault(stmt.name, []).append(child.value)
        self.classes.append(
            {
                "name": node.name,
                "line": node.lineno,
                "bases": [
                    base.id
                    for base in node.bases
                    if isinstance(base, ast.Name)
                ],
                "class_env": class_env,
                "self_attrs": self_attrs,
                "method_returns": method_returns,
            }
        )

    @staticmethod
    def _collect_local_env(node: ast.AST) -> dict[str, list[tuple[int, ast.AST]]]:
        env: dict[str, list[tuple[int, ast.AST]]] = defaultdict(list)
        for child in ast.walk(node):
            if isinstance(child, ast.Assign):
                for target in child.targets:
                    if isinstance(target, ast.Name):
                        env[target.id].append((child.lineno, child.value))
            elif isinstance(child, ast.AnnAssign) and isinstance(child.target, ast.Name) and child.value:
                env[child.target.id].append((child.lineno, child.value))
        return dict(env)

    def analyze(self) -> None:
        tree = ast.parse(self.filepath.read_text(encoding="utf-8"), filename=str(self.filepath))
        self._index_tree(tree)
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                self._collect_class_context(node)
        self._collect_functions(tree)
        self._extract_direct_calls()
        self._bind_wrappers()

    def _context_for(self, class_name: str | None) -> dict[str, Any]:
        empty = {"class_env": {}, "self_attrs": {}, "method_returns": {}}
        if class_name is None:
            return empty
        by_name = {cls["name"]: cls for cls in self.classes}
        merged = {"class_env": {}, "self_attrs": {}, "method_returns": {}}
        visiting: set[str] = set()

        def merge(name: str | None) -> None:
            if name is None or name in visiting or name not in by_name:
                return
            visiting.add(name)
            cls = by_name[name]
            for base in cls.get("bases", []):
                merge(base)
            merged["class_env"].update(cls["class_env"])
            merged["self_attrs"].update(cls["self_attrs"])
            for method, returns in cls["method_returns"].items():
                merged["method_returns"][method] = returns
            visiting.discard(name)

        merge(class_name)
        return merged

    @staticmethod
    def _enclosing_function(
        node: ast.AST, functions: Sequence[PythonFunction]
    ) -> PythonFunction | None:
        containing = [
            fn
            for fn in functions
            if getattr(fn.node, "lineno", 0) <= getattr(node, "lineno", 0)
            and getattr(fn.node, "end_lineno", 10**9) >= getattr(node, "end_lineno", 0)
        ]
        if not containing:
            return None
        return sorted(containing, key=lambda fn: (fn.node.end_lineno - fn.node.lineno))[0]

    def _all_functions(self) -> list[PythonFunction]:
        return [*self.functions, *self.module_functions]

    def _extract_direct_calls(self) -> None:
        all_functions = self._all_functions()
        for fn in all_functions:
            context = self._context_for(fn.class_name)
            resolver = _PythonRouteResolver(
                context["class_env"],
                context["self_attrs"],
                context["method_returns"],
                fn.local_env,
            )
            for node in ast.walk(fn.node):
                if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
                    continue
                attr = node.func.attr
                if attr not in PY_METHOD_MAP:
                    continue
                if not _is_http_receiver(node.func.value):
                    continue
                if not node.args:
                    continue
                method = PY_METHOD_MAP[attr]
                route_node = node.args[0]
                if attr == "open":
                    method = None
                    for kw in node.keywords:
                        if kw.arg == "method":
                            value, _ = resolver.resolve(kw.value, node.lineno)
                            if value and value.upper() in HTTP_METHODS:
                                method = value.upper()
                    if method is None:
                        if fn.is_test:
                            self.unresolved.append(
                                self._unresolved_entry(node, fn, "open() without a literal method")
                            )
                        continue
                route, via = resolver.resolve(route_node, node.lineno)
                if not _looks_like_http_route(route):
                    if fn.is_test and not isinstance(route_node, (ast.Starred,)):
                        self.unresolved.append(
                            self._unresolved_entry(node, fn, via, method)
                        )
                    continue
                self.raw_calls.append(
                    {
                        "file": str(self.filepath),
                        "line": node.lineno,
                        "function": fn.name,
                        "class": fn.class_name,
                        "is_test_function": fn.is_test,
                        "method": method,
                        "route_raw": route,
                        "resolved_via": via,
                        "node": node,
                        "route_node": route_node,
                        "fn": fn,
                    }
                )

    def _unresolved_entry(
        self,
        node: ast.Call,
        fn: PythonFunction,
        reason: str,
        method: str | None = None,
        expression: str | None = None,
    ) -> dict[str, Any]:
        if expression is None:
            expression = _name_of(node.args[0]) if node.args else ""
        return {
            "side": "python",
            "file": str(self.filepath),
            "line": node.lineno,
            "function": fn.name,
            "class": fn.class_name,
            "is_test_function": fn.is_test,
            "method": method or "",
            "expression": expression,
            "reason": reason,
        }

    def _bind_wrappers(self) -> None:
        """Resolve test-helper wrappers with parameterised routes.

        A few legacy tests route every request through helpers such as
        ``self.call("POST", "/notifications")`` where the literal path lives at
        the call site, not in the helper body.  Bind literal arguments into the
        helper's HTTP call to recover those hits.  Anything that cannot be bound
        stays in the unresolved list.
        """
        wrappers: dict[tuple[str | None, str], list[dict[str, Any]]] = defaultdict(list)
        for fn in self._all_functions():
            if fn.is_test:
                continue
            context = self._context_for(fn.class_name)
            resolver = _PythonRouteResolver(
                context["class_env"],
                context["self_attrs"],
                context["method_returns"],
                fn.local_env,
            )
            specs: list[dict[str, Any]] = []
            for node in ast.walk(fn.node):
                if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
                    continue
                attr = node.func.attr
                if attr not in PY_METHOD_MAP or not _is_http_receiver(node.func.value):
                    continue
                if not node.args:
                    continue
                method = PY_METHOD_MAP[attr]
                method_node: ast.AST | None = None
                if attr == "open":
                    method = None
                    for kw in node.keywords:
                        if kw.arg == "method":
                            method_node = kw.value
                specs.append(
                    {
                        "line": node.lineno,
                        "route_node": node.args[0],
                        "method": method,
                        "method_node": method_node,
                        "context": context,
                        "local_env": fn.local_env,
                    }
                )
            if specs:
                wrappers[(fn.class_name, fn.name)].append({"fn": fn, "specs": specs})

        if not wrappers:
            return

        # Remove the raw helper-internal hits: they are re-attributed to the
        # call sites below, and counting both would double the call count.
        suppressed = {
            id(call["node"])
            for entries in wrappers.values()
            for entry in entries
            for spec in entry["specs"]
            for call in self.raw_calls
            if call["fn"] is entry["fn"] and call["line"] == spec["line"]
        }
        self.raw_calls = [call for call in self.raw_calls if id(call["node"]) not in suppressed]

        for fn in self._all_functions():
            if fn.is_test is False and (fn.class_name, fn.name) in wrappers:
                # Do not treat helper definitions as call sites of themselves.
                continue
            context = self._context_for(fn.class_name)
            resolver = _PythonRouteResolver(
                context["class_env"],
                context["self_attrs"],
                context["method_returns"],
                fn.local_env,
            )
            for node in ast.walk(fn.node):
                if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
                    continue
                attr = node.func.attr
                candidates = wrappers.get((fn.class_name, attr)) or wrappers.get((None, attr))
                if not candidates:
                    continue
                for wrapper in candidates:
                    wrapper_fn: PythonFunction = wrapper["fn"]
                    bound: dict[str, ast.AST] = {}
                    positional = [arg for arg in node.args if not isinstance(arg, ast.Starred)]
                    for index, arg in enumerate(positional):
                        if index >= len(wrapper_fn.param_names):
                            break
                        value, _ = resolver.resolve(arg, node.lineno)
                        bound[wrapper_fn.param_names[index]] = (
                            ast.Constant(value) if value is not None else arg
                        )
                    for kw in node.keywords:
                        if kw.arg:
                            value, _ = resolver.resolve(kw.value, node.lineno)
                            bound[kw.arg] = ast.Constant(value) if value is not None else kw.value
                    for spec in wrapper["specs"]:
                        wrapper_resolver = _PythonRouteResolver(
                            spec["context"]["class_env"],
                            spec["context"]["self_attrs"],
                            spec["context"]["method_returns"],
                            spec["local_env"],
                            param_env=bound,
                        )
                        route, via = wrapper_resolver.resolve(spec["route_node"], node.lineno)
                        method = spec["method"]
                        if spec["method_node"] is not None:
                            value, _ = wrapper_resolver.resolve(spec["method_node"], node.lineno)
                            method = value.upper() if value and value.upper() in HTTP_METHODS else None
                        if method is None or not _looks_like_http_route(route):
                            if fn.is_test:
                                self.unresolved.append(
                                    self._unresolved_entry(
                                        node,
                                        fn,
                                        f"wrapper {attr} could not bind a literal route/method",
                                        method,
                                        expression=_name_of(node.args[1]) if len(node.args) > 1 else "",
                                    )
                                )
                            continue
                        self.raw_calls.append(
                            {
                                "file": str(self.filepath),
                                "line": node.lineno,
                                "function": fn.name,
                                "class": fn.class_name,
                                "is_test_function": fn.is_test,
                                "method": method,
                                "route_raw": route,
                                "resolved_via": f"wrapper:{wrapper_fn.name}",
                                "node": node,
                                "route_node": spec["route_node"],
                                "fn": fn,
                            }
                        )


def analyze_python_source(text: str, filepath: Path | str = "<synthetic>") -> dict[str, Any]:
    """Analyze one Python source string (used by the unit tests)."""
    temp_path = Path(filepath)
    if not temp_path.exists():
        # The parser only needs a path for diagnostics.  Write nothing; the
        # analyzer reads text through this shim path via a temporary subclass.
        class _TextPath(type(temp_path)):  # type: ignore[misc]
            _text = text

            def read_text(self, encoding: str = "utf-8", errors: str = "strict") -> str:  # type: ignore[override]
                return text

        temp_path = _TextPath(str(filepath))
    analyzer = PythonTestAnalyzer(temp_path)
    analyzer.analyze()
    return _python_result(analyzer)


def _python_result(analyzer: PythonTestAnalyzer) -> dict[str, Any]:
    return {
        "calls": analyzer.raw_calls,
        "functions": [
            {
                "side": "python",
                "file": str(analyzer.filepath),
                "function": fn.name,
                "class": fn.class_name,
                "line": fn.line,
                "is_test_function": fn.is_test,
                "evidence": fn.evidence,
                "http_call_count": sum(
                    1
                    for call in analyzer.raw_calls
                    if call["fn"] is fn
                ),
            }
            for fn in analyzer._all_functions()
            if any(call["fn"] is fn for call in analyzer.raw_calls) or fn.is_test
        ],
        "unresolved": analyzer.unresolved,
    }


def collect_python_tests(python_root: Path) -> dict[str, Any]:
    result: dict[str, Any] = {"calls": [], "functions": [], "files": [], "unresolved": []}
    test_root = python_root / "tests"
    for path in iter_source_files(test_root, ".py"):
        result["files"].append(str(path))
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        except SyntaxError as exc:
            result["unresolved"].append(
                {
                    "side": "python",
                    "file": str(path),
                    "line": exc.lineno,
                    "function": "",
                    "expression": "",
                    "reason": f"syntax error: {exc.msg}",
                }
            )
            continue
        analyzer = PythonTestAnalyzer(path)
        # Avoid a second parse: replace analyze's read with the already parsed
        # tree by temporarily writing it through the class hook.
        analyzer._tree = tree  # type: ignore[attr-defined]
        _analyze_with_tree(analyzer, tree)
        part = _python_result(analyzer)
        result["calls"].extend(part["calls"])
        result["functions"].extend(part["functions"])
        result["unresolved"].extend(part["unresolved"])
    return result


def _analyze_with_tree(analyzer: PythonTestAnalyzer, tree: ast.AST) -> None:
    analyzer._index_tree(tree)
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            analyzer._collect_class_context(node)
    analyzer._collect_functions(tree)
    analyzer._extract_direct_calls()
    analyzer._bind_wrappers()


