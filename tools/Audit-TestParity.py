def classify_route_bucket(route: dict[str, Any]) -> str:
    category = (route.get("category") or "").lower()
    status = (route.get("handler_status") or "").lower()
    method = (route.get("method") or "").upper()
    if category == "disabled_comment":
        return "disabled_comment"
    if status == "registered_only_405":
        return "registered_only_405"
    if method == "OPTIONS" or status == "options_not_business":
        return "options"
    if status == "handler_unknown":
        return "handler_unknown"
    if category in {"core", "conditional", "optional"}:
        return "business"
    return "csharp_extra"


def build_route_catalog(
    coverage: dict[str, Any],
    route_audit_module: Any,
    python_root: Path,
    csharp_root: Path,
) -> list[dict[str, Any]]:
    entries: dict[tuple[str, str], dict[str, Any]] = {}

    def add_pattern(entry: dict[str, Any], pattern: RoutePattern) -> None:
        entry["patterns"].append(pattern)
        entry["raw_paths"].append(
            {
                "side": pattern.side,
                "path": pattern.raw,
                "normalized": pattern.normalized,
                "source": pattern.source,
                "line": pattern.line,
                "module": pattern.module,
            }
        )

    for route in coverage.get("routes", []):
        method = (route.get("method") or "").upper()
        normalized = route.get("normalized_path") or route.get("path") or ""
        key = (method, normalized)
        entry = entries.get(key)
        if entry is None:
            entry = {
                "key": f"{method} {normalized}",
                "method": method,
                "path": normalized,
                "module": route.get("module") or canonical_module(normalized),
                "category": route.get("category"),
                "handler_status": route.get("handler_status"),
                "handler": route.get("handler"),
                "in_python_routes": True,
                "in_csharp_routes": False,
                "patterns": [],
                "raw_paths": [],
                "python_sources": [],
                "csharp_sources": [],
            }
            entries[key] = entry
        pattern = compile_route_pattern(
            route.get("path") or normalized,
            normalized,
            side="python",
        )
        pattern.source = f"{route.get('source', '')}:{route.get('line', '')}".strip(":")
        pattern.line = route.get("line")
        pattern.module = entry["module"]
        add_pattern(entry, pattern)
        entry["python_sources"].append(pattern.source)

    for route in coverage.get("csharp_routes", []):
        method = (route.get("method") or "").upper()
        normalized = route.get("normalized_path") or route.get("path") or ""
        key = (method, normalized)
        entry = entries.get(key)
        if entry is None:
            module = route.get("module") or canonical_module(normalized)
            entry = {
                "key": f"{method} {normalized}",
                "method": method,
                "path": normalized,
                "module": module,
                "category": None,
                "handler_status": None,
                "handler": None,
                "in_python_routes": False,
                "in_csharp_routes": True,
                "patterns": [],
                "raw_paths": [],
                "python_sources": [],
                "csharp_sources": [],
            }
            entries[key] = entry
        entry["in_csharp_routes"] = True
        pattern = compile_route_pattern(
            route.get("path") or normalized,
            normalized,
            side="csharp",
        )
        pattern.source = f"{route.get('source', '')}:{route.get('line', '')}".strip(":")
        pattern.line = route.get("line")
        pattern.module = entry["module"]
        add_pattern(entry, pattern)
        entry["csharp_sources"].append(pattern.source)

    for entry in entries.values():
        entry["bucket"] = classify_route_bucket(entry)
    return sorted(entries.values(), key=lambda entry: (entry["method"], entry["path"]))


def associate_call(
    call: dict[str, Any],
    catalog: Sequence[dict[str, Any]],
    normalize_fn: Any = None,
) -> tuple[dict[str, Any], dict[str, Any]] | None:
    route_text = call.get("route_raw") or ""
    path, query = strip_query_fragment(route_text)
    if not path.startswith("/"):
        return None
    call_pattern = compile_call_pattern(path)
    if normalize_fn is not None:
        try:
            call_pattern.normalized = normalize_fn(path)
        except Exception:
            call_pattern.normalized = path
    else:
        call_pattern.normalized = call_pattern.normalized
    candidates: list[tuple[tuple[int, int, int, int], dict[str, Any], dict[str, Any]]] = []
    method = (call.get("method") or "").upper()
    for entry in catalog:
        if entry["method"] != method:
            continue
        best: tuple[tuple[int, int, int, int], RoutePattern, Any] | None = None
        for pattern in entry["patterns"]:
            matched = match_route_pattern(pattern, call_pattern)
            if matched is None:
                continue
            score = route_match_score(pattern, call_pattern)
            if best is None or score > best[0]:
                best = (score, pattern, matched)
        if best is not None:
            candidates.append((best[0], entry, {"pattern": best[1], "matched": best[2]}))
    if not candidates:
        return None
    candidates.sort(key=lambda item: item[0], reverse=True)
    best_score = candidates[0][0]
    tied = [item for item in candidates if item[0] == best_score]
    chosen = tied[0]
    match_info = {
        "match_kind": "exact" if chosen[0][0] else "template_wildcard",
        "parameter_bindings": chosen[2]["matched"][0],
        "match_notes": chosen[2]["matched"][1],
        "template": chosen[2]["pattern"].raw,
        "template_side": chosen[2]["pattern"].side,
        "ambiguous": len(tied) > 1,
        "ambiguous_keys": [item[1]["key"] for item in tied] if len(tied) > 1 else [],
        "query": query,
    }
    return chosen[1], match_info


