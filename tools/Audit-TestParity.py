def _route_table(routes: Sequence[dict[str, Any]], *, include_hits: bool = True) -> list[str]:
    lines: list[str] = []
    if include_hits:
        lines.append(
            "| method | path | module | bucket | py static hits | cs static hits | py test fns | cs test methods |"
        )
        lines.append("|---|---|---|---|---:|---:|---:|---:|")
        for route in routes:
            lines.append(
                f"| {route['method']} | `{route['path']}` | {route['module']} | {route['bucket']} | "
                f"{route['python_static_hits']} | {route['csharp_static_hits']} | "
                f"{route['python_test_function_hits']} | {route['csharp_test_method_hits']} |"
            )
    else:
        lines.append("| method | path | module | bucket | python source | csharp source |")
        lines.append("|---|---|---|---|---|---|")
        for route in routes:
            lines.append(
                f"| {route['method']} | `{route['path']}` | {route['module']} | {route['bucket']} | "
                f"{', '.join(route['python_sources']) or '-'} | "
                f"{', '.join(route['csharp_sources']) or '-'} |"
            )
    return lines


def render_markdown(report: dict[str, Any]) -> str:
    lines: list[str] = []
    lines.append("# Python vs C# HTTP test parity (static lower bound)")
    lines.append("")
    lines.append(
        "Static, offline audit. No Python app import, no dotenv, no database, no network, "
        "no `dotnet` execution. A static hit is **not** a passing test."
    )
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    summary = report["summary"]
    for key in [
        "python_test_files_scanned",
        "csharp_test_files_scanned",
        "registered_route_entries_total",
        "business_routes_total",
        "business_routes_with_python_static_hit",
        "business_routes_with_csharp_static_hit",
        "business_routes_with_both_static_hits",
        "business_routes_with_neither_static_hit",
        "business_routes_python_no_static_hit",
        "business_routes_csharp_no_static_hit",
        "registered_only_405_routes_total",
        "disabled_comment_routes_total",
        "options_routes_total",
        "handler_unknown_routes_total",
        "csharp_extra_routes_total",
        "python_http_calls_unresolved",
        "csharp_http_calls_unresolved",
        "python_calls_unassociated",
        "csharp_calls_unassociated",
        "python_assertion_calls_total",
        "csharp_assertion_calls_total",
        "python_test_functions_with_http",
        "csharp_test_methods_with_http",
    ]:
        lines.append(f"- {key}: {summary[key]}")
    for side in ("python_http_calls", "csharp_http_calls"):
        data = summary[side]
        lines.append(
            f"- {side}: total={data['total']}, test_function={data['test_function_calls']}, "
            f"helper={data['helper_calls']}, associated={data['associated']}, "
            f"unassociated={data['unassociated']}"
        )
    lines.append("")
    lines.append("## Key modules")
    lines.append("")
    lines.append("| module | business routes | py hit routes | cs hit routes | py no-hit | cs no-hit |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    for name, data in report["key_modules"].items():
        lines.append(
            f"| {name} | {data['business_routes']} | {data['python_static_hit_routes']} | "
            f"{data['csharp_static_hit_routes']} | {data['python_no_static_hit_routes']} | "
            f"{data['csharp_no_static_hit_routes']} |"
        )
    lines.append("")
    lines.append("## Module summary (business routes only)")
    lines.append("")
    lines.append("| module | business | py hits | cs hits | py no-hit | cs no-hit | py calls | cs calls |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for module, data in report["module_summary"].items():
        lines.append(
            f"| {module} | {data['business_routes']} | {data['python_static_hits']} | "
            f"{data['csharp_static_hits']} | {data['python_no_static_hit']} | "
            f"{data['csharp_no_static_hit']} | {data['python_calls']} | {data['csharp_calls']} |"
        )
    lines.append("")
    lines.append("## Business routes")
    lines.append("")
    lines.extend(_route_table(report["business_routes"]))
    lines.append("")
    lines.append("## Diagnostics excluded from the business denominator")
    lines.append("")
    for title, key in [
        ("registered_only_405", "registered_only_405"),
        ("disabled_comment", "disabled_comment"),
        ("OPTIONS", "options_routes"),
        ("handler_unknown", "handler_unknown_routes"),
        ("C# extra (not in legacy)", "csharp_extra_routes"),
    ]:
        lines.append(f"### {title} ({len(report[key])})")
        lines.append("")
        if report[key]:
            lines.extend(_route_table(report[key], include_hits=False))
        else:
            lines.append("None.")
        lines.append("")
    lines.append("## Unresolved dynamic/non-literal calls")
    lines.append("")
    unresolved = [*report["python_unresolved"], *report["csharp_unresolved"]]
    if not unresolved:
        lines.append("None.")
    else:
        lines.append(
            "| side | file:line | function | method | expression | reason |"
        )
        lines.append("|---|---|---|---|---|---|")
        for item in unresolved:
            fileline = f"{item.get('file', '')}:{item.get('line', '')}"
            expression = str(item.get("expression", "")).replace("|", "\\|")
            reason = str(item.get("reason", "")).replace("|", "\\|")
            lines.append(
                f"| {item.get('side', '')} | `{fileline}` | {item.get('function', '')} | "
                f"{item.get('method', '')} | `{expression}` | {reason} |"
            )
    lines.append("")
    lines.append("## Static hits with assertion evidence")
    lines.append("")
    lines.append(
        "Each row is a source-level call site; `static_hit` is not `passed`. "
        "Assertion/status/error/header/digest columns come from the enclosing function."
    )
    lines.append("")
    lines.append(
        "| side | file:line | function | method | route | match | assertions | status | error | header | digest |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for call in [*report["python_http_calls"], *report["csharp_http_calls"]]:
        evidence = call.get("function_evidence") or {}
        lines.append(
            f"| {call['side']} | `{call['file']}:{call['line']}` | {call['function']} | "
            f"{call['method']} | `{call.get('route_key') or call.get('route_raw')}` | "
            f"{call.get('match_kind') or 'unassociated'} | "
            f"{', '.join(evidence.get('assertions', [])) or '-'} | "
            f"{', '.join(map(str, evidence.get('expected_status', []) + evidence.get('status_code_assertions', []))) or '-'} | "
            f"{', '.join(map(str, evidence.get('error_assertions', []) + evidence.get('error_code_assertions', []))) or '-'} | "
            f"{', '.join(evidence.get('header_assertions', [])) or '-'} | "
            f"{', '.join(evidence.get('digest_assertions', [])) or '-'} |"
        )
    lines.append("")
    lines.append("## Notes")
    lines.append("")
    for note in report["notes"]:
        lines.append(f"- {note}")
    lines.append("")
    return "\n".join(lines)


