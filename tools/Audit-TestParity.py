@dataclass(frozen=True)
class Segment:
    kind: str  # literal | param | int | catchall
    value: str = ""
    name: str = ""


@dataclass
class RoutePattern:
    raw: str
    normalized: str
    segments: tuple[Segment, ...]
    side: str = ""
    source: str = ""
    line: int | None = None
    module: str = ""


def _path_segments(path: str) -> list[str]:
    value = strip_query_fragment(path)[0].strip()
    if not value.startswith("/"):
        value = "/" + value
    return [part for part in value.split("/") if part != ""]


def compile_route_pattern(raw_path: str, normalized: str = "", side: str = "") -> RoutePattern:
    """Compile *raw_path* into segments, preserving converter constraints.

    ``<path:path>`` / ``{*path}`` become a catch-all; ``<int:id>`` / ``{id:int}``
    stay numeric; every other placeholder matches exactly one segment.  Query
    strings are stripped before compilation.
    """
    raw = strip_query_fragment(raw_path)[0]
    segments: list[Segment] = []
    for part in _path_segments(raw):
        if re.fullmatch(r"<path:[^<>]+>", part) or re.fullmatch(r"\{\*{1,2}[^{}]+\}", part):
            segments.append(Segment("catchall", part, "path"))
        elif re.fullmatch(r"<int:[^<>]+>", part) or re.fullmatch(
            r"\{[^{}]*:int(?:\([^)]*\))?\}", part
        ):
            segments.append(Segment("int", part, "int"))
        elif re.fullmatch(r"<[^<>]+>", part) or re.fullmatch(r"\{[^{}]+\}", part):
            inner = part.strip("<>{}")
            inner = inner.split(":", 1)[0].lstrip("*")
            segments.append(Segment("param", part, inner))
        else:
            segments.append(Segment("literal", part))
    return RoutePattern(raw=raw, normalized=normalized or raw, segments=tuple(segments), side=side)


def compile_call_pattern(route: str) -> RoutePattern:
    """Compile a request path as seen in test source.

    A ``{}`` segment is an interpolated value whose concrete value is unknown;
    it matches one route parameter.  Literal segments remain literal.
    """
    raw = strip_query_fragment(route)[0]
    segments: list[Segment] = []
    for part in _path_segments(raw):
        if part == "{}":
            segments.append(Segment("param", "{}", "value"))
        elif "{}" in part:
            # Mixed segment such as ``{id}.json``.  Match conservatively as a
            # parameter only when the route side is also non-literal.
            segments.append(Segment("param", part, "value"))
        else:
            segments.append(Segment("literal", part))
    return RoutePattern(raw=raw, normalized=raw, segments=tuple(segments), side="call")


def match_route_pattern(
    route: RoutePattern,
    call: RoutePattern,
) -> tuple[list[dict[str, Any]], list[str]] | None:
    """Return parameter bindings and notes if *call* matches *route*.

    Matching is done on segments so a generic legacy template such as
    ``/v1/{group_type}/{group_id}/applications`` correctly matches a concrete
    request to ``/v1/projects/<id>/applications``.  Bindings record the literal
    value observed in the call; no literal is invented.
    """
    if not route.segments:
        return ([], []) if not call.segments else None

    bindings: list[dict[str, Any]] = []
    notes: list[str] = []
    i = j = 0
    while i < len(route.segments):
        rseg = route.segments[i]
        if rseg.kind == "catchall":
            if j >= len(call.segments):
                return None
            remaining = call.segments[j:]
            if any(seg.kind == "literal" for seg in remaining):
                notes.append("catchall_matched_literal_segments")
            else:
                notes.append("catchall_value_unverified")
            bindings.append(
                {
                    "index": i,
                    "placeholder": rseg.name or "path",
                    "value": "/".join(seg.value for seg in remaining),
                    "constraint": "catchall",
                }
            )
            return bindings, notes
        if j >= len(call.segments):
            return None
        cseg = call.segments[j]
        if rseg.kind == "literal":
            if cseg.kind != "literal" or cseg.value != rseg.value:
                return None
        elif rseg.kind == "int":
            if cseg.kind == "literal" and not cseg.value.isdigit():
                return None
            if cseg.kind != "literal":
                notes.append("int_constraint_unverified")
        else:  # param
            if cseg.kind == "literal":
                bindings.append(
                    {
                        "index": i,
                        "placeholder": rseg.name or "value",
                        "value": cseg.value,
                        "constraint": "single_segment",
                    }
                )
                if (rseg.name or "").lower() in {"group_type", "grouptype", "scope"} and cseg.value.lower() in {
                    "team",
                    "teams",
                    "project",
                    "projects",
                }:
                    notes.append("generic_group_type_binding")
        i += 1
        j += 1
    if j != len(call.segments):
        return None
    return bindings, notes


def route_match_score(route: RoutePattern, call: RoutePattern) -> tuple[int, int, int, int]:
    exact = 1 if route.normalized == call.normalized else 0
    literals = sum(1 for seg in route.segments if seg.kind == "literal")
    catchalls = sum(1 for seg in route.segments if seg.kind == "catchall")
    params = sum(1 for seg in route.segments if seg.kind in {"param", "int"})
    return exact, literals, -catchalls, -params


