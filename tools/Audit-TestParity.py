#!/usr/bin/env python3
"""Offline, static HTTP test-parity audit between the legacy Python API and the
C# rewrite.

The audit is deliberately conservative and read-only:

* Python test sources are parsed with :mod:`ast`.  ``app`` is never imported and
  no dotenv file, database, or network service is touched.
* C# test sources are tokenized lexically (comments, regular/verbatim/raw and
  interpolated strings are handled, including nested quotes inside ``{...}``
  holes).  ``dotnet`` is never executed by this tool.
* Route registration is reused from ``tools/Audit-LegacyRoutes.py`` so the same
  normalization and static route discovery is shared by both audits.
* Only *static hits* are reported.  A static hit is not proof that a test passes;
  a missing static hit does not prove that no test exercises the route.

The output is a JSON document (plus a Markdown companion) that keeps effective
business routes, ``registered_only_405`` routes, ``disabled_comment`` routes and
OPTIONS separate so diagnostics are never mixed into the business denominator.
"""

